import { ScoreRing } from '@/components/score-ring'
import { ResultCard } from '@/components/result-card'
import type { ReviewResponse } from '@/lib/types'

import {
  FileText,
  ShieldCheck,
  TrendingUp,
  Activity,
  DollarSign,
  PackagePlus,
  AlertTriangle,
  Lightbulb,
  CheckCircle2,
  ShieldAlert,
  Wrench,
} from 'lucide-react'

type Props = {
  projectName: string
  review: ReviewResponse
}

function convertSeverity(
  severity: 'good' | 'review' | 'critical' | 'info'
): 'good' | 'warning' | 'critical' | 'info' {
  if (severity === 'review') return 'warning'
  return severity
}

export function ResultsSection({
  projectName,
  review,
}: Props) {
  const reviewSections = [
    {
      id: 'summary',
      title: 'Architecture Summary',
      icon: FileText,
      summary: review.architecture_summary,
      findings: (review.strengths ?? []).map((item, index) => ({
        label: `Strength ${index + 1}`,
        detail: item,
        severity: 'good' as const,
      })),
    },

    {
      id: 'security',
      title: 'Security Review',
      icon: ShieldCheck,
      summary: 'Security analysis generated by Amazon Bedrock.',
      findings: (review.security_review ?? []).map((item, index) => ({
        label: item.title || `Security Issue ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },

    {
      id: 'scalability',
      title: 'Scalability Analysis',
      icon: TrendingUp,
      summary: 'Scalability recommendations.',
      findings: (review.scalability_analysis ?? []).map((item, index) => ({
        label: item.title || `Scalability Issue ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },

    {
      id: 'reliability',
      title: 'Reliability Assessment',
      icon: Activity,
      summary: 'Reliability observations.',
      findings: (review.reliability_assessment ?? []).map((item, index) => ({
        label: item.title || `Reliability Issue ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },

    {
      id: 'cost',
      title: 'Cost Optimization',
      icon: DollarSign,
      summary: 'Cost optimization opportunities.',
      findings: (review.cost_optimization ?? []).map((item, index) => ({
        label: item.title || `Cost Issue ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },

    {
      id: 'missing',
      title: 'Missing AWS Services',
      icon: PackagePlus,
      summary: 'Recommended AWS services.',
      findings: (review.missing_aws_services ?? []).map((item, index) => ({
        label: item.title || `Missing Service ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },

    {
      id: 'risks',
      title: 'Potential Risks',
      icon: AlertTriangle,
      summary: 'Potential production risks.',
      findings: (review.potential_risks ?? []).map((item, index) => ({
        label: item.title || `Potential Risk ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },

    {
      id: 'recommendations',
      title: 'Recommendations',
      icon: Lightbulb,
      summary: 'Recommended next steps.',
      findings: (review.recommendations ?? []).map((item, index) => ({
        label: item.title || `Recommendation ${index + 1}`,
        detail: item.description,
        severity: convertSeverity(item.severity),
      })),
    },
  ]
const criticalCount = [
  ...(review.security_review ?? []),
  ...(review.scalability_analysis ?? []),
  ...(review.reliability_assessment ?? []),
  ...(review.cost_optimization ?? []),
  ...(review.missing_aws_services ?? []),
  ...(review.potential_risks ?? []),
  ...(review.recommendations ?? []),
].filter(item => item.severity === 'critical').length
  const scoreStats = [
    {
      icon: CheckCircle2,
      label: 'Strengths',
      value: (review.strengths ?? []).length.toString(),
      tint: 'text-[#3d7d00]',
    },
    {
      icon: ShieldAlert,
      label: 'Critical issues',
      value: criticalCount.toString(),
      tint: 'text-destructive',
    },
    {
      icon: Wrench,
      label: 'Recommendations',
      value: (review.recommendations ?? []).length.toString(),
      tint: 'text-accent',
    },
  ]
  return (
    <section
      id="results"
      className="mx-auto max-w-6xl px-4 py-16 sm:px-6"
    >
      <div className="mb-10 flex flex-col items-start gap-2">
        <span className="inline-flex items-center gap-2 rounded-full bg-primary/15 px-3 py-1 text-xs font-semibold uppercase tracking-wide text-[#9a5b00]">
          Review complete
        </span>

        <h2 className="text-3xl font-bold tracking-tight text-foreground">
          Architecture Review
          {projectName && (
            <span className="text-muted-foreground">
              {' '}
              · {projectName}
            </span>
          )}
        </h2>

        <p className="max-w-2xl text-base text-muted-foreground">
          {review.architecture_summary}
        </p>
      </div>

      <div className="mb-8 grid gap-6 rounded-3xl border border-border bg-card p-8 shadow-sm lg:grid-cols-[auto_1fr] lg:items-center">
        <div className="flex justify-center lg:justify-start">
          <ScoreRing
            score={review.production_readiness_score}
          />
        </div>

        <div>
          <h3 className="text-xl font-semibold">
            Production Readiness Score
          </h3>

          <p className="mt-2 text-sm text-muted-foreground">
            Architecture Pattern:{' '}
            <strong>{review.architecture_pattern.name}</strong>
            {' • '}
            Confidence:{' '}
            <strong>
              {review.architecture_pattern.confidence}%
            </strong>
          </p>

          <p className="mt-3 text-sm text-muted-foreground">
            {review.architecture_pattern.reason}
          </p>

          <dl className="mt-6 grid gap-4 sm:grid-cols-3">
            {scoreStats.map((stat) => {
              const Icon = stat.icon

              return (
                <div
                  key={stat.label}
                  className="rounded-2xl border border-border bg-secondary/60 p-4"
                >
                  <Icon
                    className={`h-5 w-5 ${stat.tint}`}
                  />

                  <dt className="mt-2 text-xs font-medium uppercase tracking-wide text-muted-foreground">
                    {stat.label}
                  </dt>

                  <dd className="mt-1 text-lg font-semibold">
                    {stat.value}
                  </dd>
                </div>
              )
            })}
          </dl>
        </div>
      </div>

      <div className="grid items-start gap-6 md:grid-cols-2 lg:grid-cols-3">
        {reviewSections.map((section) => (
          <ResultCard
            key={section.id}
            section={section}
          />
        ))}
      </div>
    </section>
  )
}  